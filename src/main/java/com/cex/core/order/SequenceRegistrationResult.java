package com.cex.core.order;

/**
 * 单订单权威序号事件的登记结果。
 *
 * <p>核心能力：区分可立即处理、等待空洞、幂等重复和已经消费的事件。</p>
 * <p>线程安全：枚举不可变；登记动作仍须由订单所属用户锁串行化。</p>
 * <p>使用限制：协议冲突和缓存背压通过异常报告，不编码为枚举值。</p>
 */
public enum SequenceRegistrationResult {
    /** 事件占用下一权威序号，可以尝试处理。 */
    READY,
    /** 事件位于序号空洞之后，已进入有界缓存。 */
    BUFFERED,
    /** 相同序号和载荷已经登记，本次为幂等重放。 */
    DUPLICATE,
    /** 事件序号已经消费，本次为过期到达。 */
    STALE
}

package com.cex.core.order;

/**
 * 订单状态机的可见状态。
 * 核心能力是描述订单在创建、风控、成交和取消之间的收敛结果；枚举不可变且线程安全。
 * 限制：终态冲突的先后裁决由状态机处理，状态值不单独携带事件历史。
 */
public enum OrderStatus {
    /** 尚未获得创建事实的初始状态。 */
    INIT,
    /** 已创建且可等待成交的有效新单状态。 */
    NEW,
    /** 风控要求人工或异步审批时的暂挂状态。 */
    RISK_HOLD,
    /** 已成交并完成资金结算的终态。 */
    FILLED,
    /** 已取消或审批拒绝且完成解冻的终态。 */
    CANCELED
}
